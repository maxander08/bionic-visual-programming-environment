// Builds src/i18n/zh-Hant.ts from the Simplified dictionary with OpenCC (Simplified → Traditional, Taiwan phrases),
// then applies the few overrides where the generic conversion picks the wrong sense for this application.
// Run: npx vite-node scripts/i18n/gen-hant.ts
import fs from 'fs';
// @ts-ignore no types
import * as OpenCC from 'opencc-js';
import { zhHans } from '../../src/i18n/zh-Hans';

const conv = OpenCC.Converter({ from: 'cn', to: 'twp' });
// Applied to the converted text. OpenCC reads 质量 as “quality”; in this app it is the physical mass.
const FIX: [RegExp, string][] = [[/品質/g, '質量'], [/互動/g, '互動'], [/程式碼/g, '程式碼'], [/資料庫/g, '資料庫'], [/（儒略年/g, '（儒略年']];
const out: Record<string, string> = {};
for (const [k, v] of Object.entries(zhHans)) {
  let t: string = conv(v);
  if (/\bmass\b/i.test(k)) for (const [re, to] of FIX) t = t.replace(re, to);
  out[k] = t;
}
fs.writeFileSync('src/i18n/zh-Hant.ts', `// GENERATED by scripts/i18n/gen-hant.ts (OpenCC s2twp) from zh-Hans.ts. Do not edit by hand.\nexport const zhHant: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log('hant entries:', Object.keys(out).length);
