// Builds src/i18n/hans/docs.ts: pairs the English module docs (read live from the registry) with the translations
// kept in scripts/i18n/*.zh.txt (one "<Kind><index>|<text>" line each). Run: npx vite-node scripts/i18n/build-docs.ts
import fs from 'fs';
import { MODULES } from '../../src/core/registry';

const uniq = (a: (string | undefined)[]) => [...new Set(a.filter(Boolean) as string[])];
const en: Record<string, string[]> = {
  S: uniq(MODULES.map((m) => m.doc.summary)),
  P: uniq(MODULES.flatMap((m) => m.params.map((p: any) => p.doc))),
};
const out: Record<string, string> = {};
for (const file of ['summary', 'param']) {
  for (const line of fs.readFileSync(`scripts/i18n/${file}.zh.txt`, 'utf8').split('\n')) {
    const m = /^([A-Z])(\d+)\|(.+)$/.exec(line);
    if (!m) continue;
    const key = en[m[1]][Number(m[2])];
    if (key) out[key] = m[3].trim();
  }
}
fs.writeFileSync('src/i18n/hans/docs.ts', `// GENERATED by scripts/i18n/build-docs.ts from scripts/i18n/*.zh.txt. Do not edit by hand.\nexport const docs: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log('docs entries:', Object.keys(out).length);
