// Regenerates src/core/data/land.ts, the outlines drawn on the Globe, from the Natural Earth 110 m data of the `world-atlas` package
// (public domain). Every arc of the topology is one polyline; arcs used by two countries are borders, the others are coastlines.
//   npm install --no-save world-atlas && node scripts/build-land.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-110m.json', 'utf8'));
const uses = new Array(topo.arcs.length).fill(0);
const walk = (a) => { if (typeof a === 'number') uses[a < 0 ? ~a : a]++; else a.forEach(walk); };
topo.objects.countries.geometries.forEach((g) => walk(g.arcs));
const { scale, translate } = topo.transform;
const lines = topo.arcs.map((arc, i) => {
  let x = 0, y = 0;
  const pts = arc.map(([dx, dy]) => { x += dx; y += dy; return [Math.round((x * scale[0] + translate[0]) * 10) / 10, Math.round((y * scale[1] + translate[1]) * 10) / 10]; });
  return { b: uses[i] > 1 ? 1 : 0, p: pts.flat() };
});
const out = `// GENERATED by scripts/build-land.mjs from Natural Earth 110 m (public domain) — do not edit by hand.
// Each line: [kind, lon, lat, lon, lat, …]; kind 0 = coastline, 1 = border between two countries.
export const LAND_LINES: number[][] = ${JSON.stringify(lines.map((l) => [l.b, ...l.p]))};
`;
writeFileSync('src/core/data/land.ts', out);
console.log(lines.length, 'lines', (out.length / 1024).toFixed(0), 'KB');
