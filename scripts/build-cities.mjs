// Regenerates src/core/data/cities.ts from the public-domain-ish GeoNames dumps (CC BY 4.0, https://www.geonames.org).
//
//   curl -O https://download.geonames.org/export/dump/cities1000.zip && unzip cities1000.zip
//   curl -O https://download.geonames.org/export/dump/countryInfo.txt
//   node scripts/build-cities.mjs <dir-with-both-files>
//
// For every country it keeps the 30 most populous cities with their IANA time zone.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2] ?? '.';
const PER_COUNTRY = 30;

const countryName = {};
for (const line of readFileSync(join(dir, 'countryInfo.txt'), 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const f = line.split('\t');
  countryName[f[0]] = f[4];
}

const byCountry = {};
for (const line of readFileSync(join(dir, 'cities1000.txt'), 'utf8').split('\n')) {
  if (!line) continue;
  const f = line.split('\t');
  const [name, cc, pop, tz] = [f[1], f[8], Number(f[14]) || 0, f[17]];
  if (!name || !cc || !tz) continue;
  (byCountry[cc] ??= []).push({ name, pop, tz });
}

const tzList = [];
const tzIdx = new Map();
const idx = (tz) => {
  if (!tzIdx.has(tz)) { tzIdx.set(tz, tzList.length); tzList.push(tz); }
  return tzIdx.get(tz);
};

const countries = Object.keys(byCountry)
  .sort((a, b) => (countryName[a] ?? a).localeCompare(countryName[b] ?? b))
  .map((cc) => {
    const seen = new Set();
    const cities = byCountry[cc]
      .sort((a, b) => b.pop - a.pop)
      .filter((c) => (seen.has(c.name) ? false : (seen.add(c.name), true)))
      .slice(0, PER_COUNTRY)
      .map((c) => [c.name, idx(c.tz), c.pop]);
    return [cc, countryName[cc] ?? cc, cities];
  });

const data = { tz: tzList, c: countries };
const out = `// GENERATED by scripts/build-cities.mjs — do not edit by hand.
// The ${PER_COUNTRY} most populous cities of every country (GeoNames, CC BY 4.0). Row: [name, timeZoneIndex, population].
export interface CityData { tz: string[]; c: [cc: string, country: string, cities: [name: string, tz: number, pop: number][]][] }
export const CITY_DATA: CityData = ${JSON.stringify(data)};
`;
mkdirSync('src/core/data', { recursive: true });
writeFileSync('src/core/data/cities.ts', out);
console.log(`${countries.length} countries, ${countries.reduce((n, c) => n + c[2].length, 0)} cities, ${tzList.length} zones, ${(out.length / 1024).toFixed(0)} KB`);
